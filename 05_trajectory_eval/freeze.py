"""
Module 5: Emit FROZEN.md, the freeze record for schema, prompt, and bands.

FROZEN.md is the contract that makes the Aug 12 freeze enforceable: it
records the hashes of everything whose change would invalidate cached XLA
shapes or make results incomparable. A run whose metadata hashes disagree
with FROZEN.md is a run against a different experiment.

The file regenerates from source (this script), never by hand, so the
hashes in it are always the hashes of the code as committed. Band
boundaries enter from the band report once the adjudicated corpus exists;
until then the file says so explicitly instead of holding placeholders that
look like data.

Usage:
    python 05_trajectory_eval/freeze.py                       # pre-freeze draft
    python 05_trajectory_eval/freeze.py \
        --bands results/band_report.json --freeze-date 2026-08-12
"""

import argparse
import json
from pathlib import Path

from canonicalize import TRUNCATION_STRATEGY
from prompts import PROMPT_VERSION, prompt_hash
from schema import STATE_VERDICT_SCHEMA, VERDICT_SCHEMA, record_schema_fingerprint, schema_hash


def render_frozen(band_report: dict | None, freeze_date: str | None) -> str:
    frozen = band_report is not None and freeze_date is not None and not band_report.get("metadata", {}).get("staged")
    status = "FROZEN" if frozen else "PRE-FREEZE DRAFT (do not treat as frozen)"
    lines = [
        "# FROZEN: Part 2 schema, prompt, and band record",
        "",
        f"**Status: {status}**",
        "",
        "Regenerated by `freeze.py`; never edited by hand. A TPU run whose metadata disagrees with any",
        "hash below is a run against a different experiment and its numbers do not belong in the tables.",
        "",
        "| Item | Value |",
        "|---|---|",
        f"| Record schema fingerprint | `{record_schema_fingerprint()}` |",
        f"| Verdict schema hash (six-call, `STATE_VERDICT_SCHEMA`) | `{schema_hash(STATE_VERDICT_SCHEMA)}` |",
        f"| Verdict schema hash (single-call, `VERDICT_SCHEMA`) | `{schema_hash(VERDICT_SCHEMA)}` |",
        f"| Judge prompt version | `{PROMPT_VERSION}` |",
        f"| Judge prompt hash | `{prompt_hash()}` |",
        f"| Windowing strategy | `{TRUNCATION_STRATEGY}` |",
        f"| Freeze date | {freeze_date if frozen else 'PENDING (target 2026-08-12)'} |",
    ]
    if band_report is None:
        lines += [
            "| Band boundaries | PENDING: requires the adjudicated corpus and the target tokenizer |",
            "| Band padding waste | PENDING |",
        ]
    else:
        meta = band_report.get("metadata", {})
        proposal = band_report["proposal"]
        staged_note = " (PREVIEW from staged input, not freezable)" if meta.get("staged") else ""
        lines += [
            f"| Band boundaries (token ceilings) | `{proposal['ceilings']}`{staged_note} |",
            f"| Band padding waste | {proposal['padding_waste']:.1%}{staged_note} |",
            f"| Band tokenizer | `{meta.get('tokenizer', 'unknown')}` |",
            f"| Band source corpus | `{meta.get('corpus', 'unknown')}` |",
        ]
    lines += [
        "",
        "After the freeze: schema and prompt changes wait for Part 3. A gap found post-freeze goes in the",
        "E4 friction log, and the run proceeds against the frozen definitions.",
        "",
    ]
    return "\n".join(lines)


def main(args: argparse.Namespace) -> None:
    band_report = None
    if args.bands:
        with open(args.bands, encoding="utf-8") as f:
            band_report = json.load(f)
    content = render_frozen(band_report, args.freeze_date)
    out = Path(args.out)
    out.write_text(content, encoding="utf-8", newline="\n")
    print(f"Wrote {out}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Emit FROZEN.md from source hashes and the band report")
    parser.add_argument("--bands", default=None, help="Path to results/band_report.json (omit while pending)")
    parser.add_argument("--freeze-date", default=None, help="Set only when actually freezing (e.g. 2026-08-12)")
    parser.add_argument("--out", default="05_trajectory_eval/FROZEN.md")
    main(parser.parse_args())
